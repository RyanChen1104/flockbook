// Builds the phone PWA (web/) into Sources/HerdrKit/HubWebAssets.swift, so the Swift build never needs Node.
//   node scripts/web-build.mjs          type-check (deno), strip types (Node's built-in), write the Swift file
//   node scripts/web-build.mjs --check  fail when the Swift file is not what the sources give
// No packages: Node 24 strips TypeScript types itself; `deno check` does the type check.
import { stripTypeScriptTypes } from "node:module";
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const web = join(root, "web");
const out = join(root, "Sources/HerdrKit/HubWebAssets.swift");
const check = process.argv.includes("--check");

const types = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".svg": "image/svg+xml",
  ".webmanifest": "application/manifest+json",
};

const sources = readdirSync(join(web, "src")).filter((f) => f.endsWith(".ts")).sort();
execFileSync("deno", ["check", "--quiet", "--config", join(web, "deno.json"), ...sources.map((f) => join(web, "src", f))], { stdio: "inherit" });

const files = {};
for (const f of ["index.html", "style.css", "manifest.webmanifest", "icon.svg"]) files[f] = readFileSync(join(web, f));
for (const f of sources) {
  const js = stripTypeScriptTypes(readFileSync(join(web, "src", f), "utf8"), { mode: "strip" });
  files[f.replace(/\.ts$/, ".js")] = Buffer.from(js);
}

const names = Object.keys(files).sort();
let swift = "// Generated by scripts/web-build.mjs from web/. Do not edit.\nimport Foundation\n\nextension HubWeb {\n";
swift += "    public static let bundled = Assets(files: [\n";
for (const n of names) {
  const ext = n.slice(n.lastIndexOf("."));
  swift += `        ${JSON.stringify(n)}: File(type: ${JSON.stringify(types[ext])}, body: Data(base64Encoded: ${JSON.stringify(files[n].toString("base64"))})!),\n`;
}
swift += "    ])\n}\n";

if (check) {
  const same = existsSync(out) && readFileSync(out, "utf8") === swift;
  console.log(same ? `web-build: up to date (${names.length} files)` : "web-build: HubWebAssets.swift is stale; run node scripts/web-build.mjs");
  process.exit(same ? 0 : 1);
}
writeFileSync(out, swift);
console.log(`web-build: wrote ${names.length} files (${names.join(", ")})`);
